# Declaracion de variables
nombre = "Hernan Varas"
edad = 30
print("Hola, mi nombre es", nombre, "y tengo", edad, "años.")
apellido: str = "Varas"
print("Mi apellido es", apellido)

print("Tipos de Variables:")
print("Tipo Texto o String")
delito = "Robo agravado"
print(type(delito))
print("Tipo Entero o Integer")
numero_expediente = 2026001
print(type(numero_expediente))
print("Tipo Decimal o Float")
monto_robado = 1250.75
print(type(monto_robado))
print("Tipo Booleano o Bool")
caso_abierto = True
print(type(caso_abierto))

evidencias = 5
print(evidencias)
evidencias = 5 + 5
print(evidencias)
evidencias += 5
print(evidencias)